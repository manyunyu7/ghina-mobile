#!/usr/bin/env bash
# Regenerates the per-mascot launcher icons (the launcher icon — and with it the
# Android 12+ splash — follows "Pilih maskot"; see LauncherIcon.kt).
#
#   tool/mascot_icons.sh
#
# Renders every MascotKind but the tree (that one is ic_launcher itself) with
# test/tool/app_icon_render_test.dart, then writes one density each (Android
# scales down): drawable-xxxhdpi/ic_launcher_fg_<id>.png (adaptive foreground,
# 108dp = 432px), mipmap-xxxhdpi/ic_launcher_<id>.png (legacy, 192px) and
# mipmap-anydpi-v26/ic_launcher_<id>.xml. The aliases live in AndroidManifest.xml.
# Also the notification small icons drawable-*/ic_stat_<id>.png
# (tool/mascot_stat_icons.py, needs Pillow; see FlutterNotificationGateway).
set -euo pipefail
cd "$(dirname "$0")/.."

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
GHINA_MASCOT_ICON_OUT="$TMP" flutter test test/tool/app_icon_render_test.dart >/dev/null

RES=android/app/src/main/res
for fg in "$TMP"/*_foreground.png; do
  id=$(basename "$fg" _foreground.png)
  sips -z 432 432 "$fg" --out "$RES/drawable-xxxhdpi/ic_launcher_fg_$id.png" >/dev/null
  sips -z 192 192 "$TMP/$id.png" --out "$RES/mipmap-xxxhdpi/ic_launcher_$id.png" >/dev/null
  cat > "$RES/mipmap-anydpi-v26/ic_launcher_$id.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/mascot_icons.sh -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_fg_$id"/>
</adaptive-icon>
XML
  echo "$id"
done
python3 tool/mascot_stat_icons.py "$TMP" "$RES"
