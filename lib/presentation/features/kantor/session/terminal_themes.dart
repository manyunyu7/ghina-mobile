/// The preset with [id]; an unknown id falls back to the default.
TermThemeDef termThemeById(String? id) =>
    termThemes.firstWhere((t) => t.id == id, orElse: () => termThemes.first);

/// Terminal fonts. The files live in `assets/fonts` (see `pubspec.yaml`).
enum TermFace {
  jetbrains('JetBrains Mono', 'JetBrainsMono'),
  ubuntu('Ubuntu Mono', 'UbuntuMono'),
  fira('Fira Code', 'FiraCode'),
  source('Source Code Pro', 'SourceCodePro'),
  plex('IBM Plex Mono', 'IBMPlexMono'),
  roboto('Roboto Mono', 'RobotoMono');

  const TermFace(this.label, this.family);
  final String label;

  /// Family name as registered in `pubspec.yaml`.
  final String family;

  /// Falls back to the system monospace for glyphs the font lacks (box
  /// drawing, symbols, emoji).
  static const fallback = ['monospace', 'Menlo', 'Courier'];
}

