/// A terminal color preset, ported from `TERM_THEMES` of the web Kantor
/// (`web/js/view-prefs.js`): background, text, cursor, selection and the 16
/// ANSI colors (Claude Code uses them for diffs and code highlighting).
@immutable
class TermThemeDef {
  const TermThemeDef({
    required this.id,
    required this.label,
    required this.background,
    required this.foreground,
    required this.cursor,
    required this.selection,
    required this.ansi,
    this.light = false,
  });

  final String id;
  final String label;
  final bool light;
  final Color background;
  final Color foreground;
  final Color cursor;
  final Color selection;

  /// black, red, green, yellow, blue, magenta, cyan, white, then the same
  /// eight bright.
  final List<Color> ansi;

  /// The xterm theme of this preset.
  TerminalTheme toTerminalTheme() => TerminalTheme(
    cursor: cursor,
    selection: selection,
    foreground: foreground,
    background: background,
    black: ansi[0],
    red: ansi[1],
    green: ansi[2],
    yellow: ansi[3],
    blue: ansi[4],
    magenta: ansi[5],
    cyan: ansi[6],
    white: ansi[7],
    brightBlack: ansi[8],
    brightRed: ansi[9],
    brightGreen: ansi[10],
    brightYellow: ansi[11],
    brightBlue: ansi[12],
    brightMagenta: ansi[13],
    brightCyan: ansi[14],
    brightWhite: ansi[15],
    searchHitBackground: const Color(0xFFFFD84D),
    searchHitBackgroundCurrent: const Color(0xFFF28C28),
    searchHitForeground: Colors.black,
  );
}

